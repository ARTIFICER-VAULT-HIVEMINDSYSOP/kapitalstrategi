export const STRINGS = { sv, en, uk }

const listeners = new Set()
let priceKey = null

/** Under Historia byts sim.price mot en neutral etikett. null återställer. */
export function setPriceKey(key) {
  priceKey = key || null
}

function readStored() {
  try {
    const v = localStorage.getItem(LANG_KEY)
    if (v === 'sv' || v === 'en' || v === 'uk') return v
  } catch {
    /* storage unavailable */
  }
  return 'sv'
}

function persistQuery() {
  try {
    const q = new URLSearchParams(location.search).get('lang')
    if (q === 'sv' || q === 'en' || q === 'uk') localStorage.setItem(LANG_KEY, q)
  } catch {
    /* ignore */
  }
}

export function getLang() {
  return readStored()
}

function emit() {
  applyHtmlLang()
  for (const fn of listeners) fn(getLang())
}

export function setLang(lang) {
  if (lang !== 'sv' && lang !== 'en' && lang !== 'uk') return
  try {
    localStorage.setItem(LANG_KEY, lang)
  } catch {
    /* ignore */
  }
  emit()
}

export function onLang(fn) {
  listeners.add(fn)
  return () => listeners.delete(fn)
}

export function t(key, vars) {
  if (key === 'sim.price' && priceKey) key = priceKey
  const lang = getLang()
  let s = STRINGS[lang]?.[key] ?? STRINGS.sv[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.split('{' + k + '}').join(String(v))
  }
  return s
}

export function helpLine(mode, orientation) {
  const o = orientation || (mode === 'raket' ? MODES.raket.orientation : mode === 'rabbit' ? MODES.rabbitHole.orientation : MODES.trendRider.orientation)
  return instructionText(o, t)
}

export function applyHtmlLang() {
  if (typeof document === 'undefined') return
  document.documentElement.lang = getLang()
}

export function applyStatic(root = typeof document !== 'undefined' ? document : null) {
  if (!root) return
  applyHtmlLang()
  root.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n')
    if (el.tagName === 'META') el.setAttribute('content', t(key))
    else if (el.tagName === 'TITLE') {
      el.textContent = t(key)
      document.title = t(key)
    } else el.textContent = t(key)
  })
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria'))))
  root.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.getAttribute('data-i18n-title'))
  })
  root.querySelectorAll('.lang-switcher-btn').forEach((btn) => {
    const on = btn.getAttribute('data-lang') === getLang()
    btn.classList.toggle('active', on)
    btn.setAttribute('aria-pressed', on ? 'true' : 'false')
  })
  const group = root.querySelector('.lang-switcher')
  if (group) group.setAttribute('aria-label', t('lang.group'))
}

export function mountSwitcher(host) {
  if (!host || host.querySelector('.lang-switcher')) return null
  const box = document.createElement('div')
  box.className = 'lang-switcher'
  box.setAttribute('role', 'group')
  for (const id of LANGS) {
    const b = document.createElement('button')
    b.type = 'button'
    b.className = 'lang-switcher-btn'
    b.setAttribute('data-lang', id)
    b.setAttribute('lang', id === 'uk' ? 'uk' : id)
    b.textContent = id === 'uk' ? 'UA' : id.toUpperCase()
    b.title = t(id === 'sv' ? 'lang.sv' : id === 'en' ? 'lang.en' : 'lang.uk')
    b.addEventListener('click', () => setLang(id))
    box.appendChild(b)
  }
  host.appendChild(box)
  applyStatic(document)
  return box
}

function installWindow() {
  if (typeof window === 'undefined') return
  window.__trT = t
  window.__trGetLang = getLang
  window.__trSubscribeLang = (cb) => onLang(cb)
  window.__trHint = (action) => HINTS['1p'][action] ?? ''
  window.__trHelp = () => helpLine('1p')
  window.__trSetLang = setLang
}

installWindow()
if (typeof window !== 'undefined') {
  persistQuery()
  applyHtmlLang()
  window.addEventListener('storage', (e) => {
    if (e.key === LANG_KEY) emit()
  })
}

export function bootStatic() {
  applyStatic(document)
  const slot = document.querySelector('[data-lang-slot]')
  if (slot) mountSwitcher(slot)
  onLang(() => applyStatic(document))
}
